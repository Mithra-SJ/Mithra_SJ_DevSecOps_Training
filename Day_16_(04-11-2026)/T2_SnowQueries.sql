CREATE OR REPLACE TABLE CLEAN_ORDERS AS
SELECT
    O_ORDERKEY AS ORDER_ID,
    O_CUSTKEY AS CUSTOMER_ID,
    UPPER(TRIM(O_ORDERSTATUS)) AS ORDER_STATUS,
    ROUND(O_TOTALPRICE, 2) AS TOTAL_AMOUNT,
    O_ORDERDATE AS ORDER_DATE,
    UPPER(TRIM(O_ORDERPRIORITY)) AS ORDER_PRIORITY
FROM RAW_ORDERS
WHERE O_TOTALPRICE > 0;

CREATE OR REPLACE TABLE CUSTOMER_SALES AS
SELECT
    O.ORDER_ID,
    O.CUSTOMER_ID,
    C.C_NAME AS CUSTOMER_NAME,
    C.C_MKTSEGMENT AS MARKET_SEGMENT,
    O.ORDER_STATUS,
    O.TOTAL_AMOUNT,
    O.ORDER_DATE
FROM CLEAN_ORDERS O
INNER JOIN RAW_CUSTOMERS C
    ON O.CUSTOMER_ID = C.C_CUSTKEY;

CREATE OR REPLACE TABLE SALES_WITH_CATEGORY AS
SELECT
    *,
    CASE
        WHEN TOTAL_AMOUNT >= 100000 THEN 'HIGH VALUE'
        WHEN TOTAL_AMOUNT >= 50000 THEN 'MEDIUM VALUE'
        ELSE 'LOW VALUE'
    END AS SALES_CATEGORY
FROM CUSTOMER_SALES;

CREATE OR REPLACE TABLE SALES_SUMMARY AS
SELECT
    MARKET_SEGMENT,
    COUNT(*) AS TOTAL_ORDERS,
    ROUND(SUM(TOTAL_AMOUNT), 2) AS TOTAL_SALES,
    ROUND(AVG(TOTAL_AMOUNT), 2) AS AVERAGE_ORDER_VALUE
FROM SALES_WITH_CATEGORY
GROUP BY MARKET_SEGMENT;

SELECT *
FROM SALES_SUMMARY
ORDER BY TOTAL_SALES DESC;

