CREATE WAREHOUSE SALES_WH
WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE SALES_DB;

CREATE SCHEMA SALES_DB.SALES_SCHEMA;

USE WAREHOUSE SALES_WH;

USE DATABASE SALES_DB;

USE SCHEMA SALES_SCHEMA;

SELECT
    CURRENT_DATABASE(),
    CURRENT_SCHEMA(),
    CURRENT_WAREHOUSE();

CREATE OR REPLACE TABLE CUSTOMERS (
    CUSTOMERID NUMBER,
    CUSTOMERNAME VARCHAR(100),
    CITY VARCHAR(100),
    CUSTOMERSEGMENT VARCHAR(50)
);

CREATE OR REPLACE TABLE PRODUCTS (
    PRODUCTID NUMBER,
    PRODUCTNAME VARCHAR(100),
    CATEGORY VARCHAR(100),
    UNITPRICE NUMBER(10,2)
);

CREATE OR REPLACE TABLE ORDERS (
    ORDERID NUMBER,
    ORDERDATE DATE,
    CUSTOMERID NUMBER,
    PRODUCTID NUMBER,
    QUANTITY NUMBER,
    DISCOUNTPCT NUMBER(5,2),
    PAYMENTMODE VARCHAR(50),
    ORDERSTATUS VARCHAR(50)
);

SHOW TABLES IN SCHEMA SALES_DB.SALES_SCHEMA;

CREATE OR REPLACE FILE FORMAT SALES_CSV_FORMAT
TYPE = 'CSV'
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
NULL_IF = ('NULL', 'null')
EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE SALES_STAGE
FILE_FORMAT = SALES_CSV_FORMAT;

SHOW STAGES IN SCHEMA SALES_DB.SALES_SCHEMA;

LIST @SALES_STAGE;

COPY INTO CUSTOMERS
FROM @SALES_STAGE/Customers.csv
FILE_FORMAT = (FORMAT_NAME = SALES_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO PRODUCTS
FROM @SALES_STAGE/Products.csv
FILE_FORMAT = (FORMAT_NAME = SALES_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ORDERS
FROM @SALES_STAGE/Orders.csv
FILE_FORMAT = (FORMAT_NAME = SALES_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_CUSTOMERS
FROM CUSTOMERS;

SELECT COUNT(*) AS TOTAL_PRODUCTS
FROM PRODUCTS;

SELECT COUNT(*) AS TOTAL_ORDERS
FROM ORDERS;

SELECT * FROM CUSTOMERS LIMIT 10;

SELECT * FROM PRODUCTS LIMIT 10;

SELECT * FROM ORDERS LIMIT 10;

SELECT O.*
FROM ORDERS O
LEFT JOIN CUSTOMERS C
    ON O.CUSTOMERID = C.CUSTOMERID
WHERE C.CUSTOMERID IS NULL;

SELECT O.*
FROM ORDERS O
LEFT JOIN PRODUCTS P
    ON O.PRODUCTID = P.PRODUCTID
WHERE P.PRODUCTID IS NULL;

CREATE OR REPLACE VIEW SALES_ANALYSIS AS
SELECT
    O.ORDERID,
    O.ORDERDATE,
    C.CUSTOMERID,
    C.CUSTOMERNAME,
    C.CITY,
    C.CUSTOMERSEGMENT,
    P.PRODUCTID,
    P.PRODUCTNAME,
    P.CATEGORY,
    O.QUANTITY,
    P.UNITPRICE,
    O.DISCOUNTPCT,
    O.PAYMENTMODE,
    O.ORDERSTATUS,

    O.QUANTITY * P.UNITPRICE AS GROSS_REVENUE,

    O.QUANTITY * P.UNITPRICE *
    (1 - O.DISCOUNTPCT) AS NET_REVENUE

FROM ORDERS O

LEFT JOIN CUSTOMERS C
    ON O.CUSTOMERID = C.CUSTOMERID

LEFT JOIN PRODUCTS P
    ON O.PRODUCTID = P.PRODUCTID;

SELECT *
FROM SALES_ANALYSIS
LIMIT 20;

SELECT
    SUM(NET_REVENUE) AS TOTAL_REVENUE,
    SUM(GROSS_REVENUE) AS GROSS_REVENUE,
    SUM(GROSS_REVENUE - NET_REVENUE) AS TOTAL_DISCOUNT
FROM SALES_ANALYSIS;

SELECT
    CATEGORY,
    SUM(NET_REVENUE) AS TOTAL_REVENUE
FROM SALES_ANALYSIS
GROUP BY CATEGORY
ORDER BY TOTAL_REVENUE DESC;

SELECT
    CITY,
    SUM(NET_REVENUE) AS TOTAL_REVENUE
FROM SALES_ANALYSIS
GROUP BY CITY
ORDER BY TOTAL_REVENUE DESC;

SELECT
    ORDERSTATUS,
    COUNT(*) AS TOTAL_ORDERS
FROM SALES_ANALYSIS
GROUP BY ORDERSTATUS;

