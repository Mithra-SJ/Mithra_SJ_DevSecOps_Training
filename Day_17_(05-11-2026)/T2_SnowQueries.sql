SELECT
    ORDERID,
    ORDERDATE,
    CUSTOMERID,
    PRODUCTID,
    QUANTITY,
    DISCOUNTPCT
FROM SALES
ORDER BY ORDERDATE;

SELECT S.CUSTOMERID
FROM SALES S
LEFT JOIN CUSTOMERS C
ON S.CUSTOMERID = C.CUSTOMERID
WHERE C.CUSTOMERID IS NULL;

SELECT S.PRODUCTID
FROM SALES S
LEFT JOIN PRODUCTS P
ON S.PRODUCTID = P.PRODUCTID
WHERE P.PRODUCTID IS NULL;

CREATE OR REPLACE VIEW SALES_ANALYTICS AS

SELECT
    S.ORDERID,
    S.ORDERDATE,
    S.CUSTOMERID,
    C.CUSTOMERNAME,
    C.CITY,
    C.CUSTOMERSEGMENT,

    S.PRODUCTID,
    P.PRODUCTNAME,
    P.CATEGORY,

    P.UNITPRICE,
    S.QUANTITY,
    S.DISCOUNTPCT,

    S.PAYMENTMODE,
    S.ORDERSTATUS,

    P.UNITPRICE * S.QUANTITY AS GROSS_REVENUE,

    P.UNITPRICE * S.QUANTITY * S.DISCOUNTPCT
        AS DISCOUNT_AMOUNT,

    P.UNITPRICE * S.QUANTITY *
        (1 - S.DISCOUNTPCT) AS NET_REVENUE

FROM SALES S

JOIN CUSTOMERS C
    ON S.CUSTOMERID = C.CUSTOMERID

JOIN PRODUCTS P
    ON S.PRODUCTID = P.PRODUCTID;

SELECT * FROM SALES_ANALYTICS;

DROP VIEW IF EXISTS SALES_ANALYTICS;

DROP TABLE IF EXISTS SALES;

DROP TABLE IF EXISTS CUSTOMERS;

DROP TABLE IF EXISTS PRODUCTS;

DROP STAGE IF EXISTS SALES_STAGE;

DROP FILE FORMAT IF EXISTS CSV_FORMAT;

DROP SCHEMA IF EXISTS SALES_SCHEMA;

DROP DATABASE IF EXISTS SALES_DB;

DROP WAREHOUSE IF EXISTS SALES_WH;