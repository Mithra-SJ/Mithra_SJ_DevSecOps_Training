CREATE DATABASE ONLINE_RETAIL_DB;

SHOW DATABASES;

CREATE SCHEMA ONLINE_RETAIL_DB.RETAIL_SCHEMA;

SHOW SCHEMAS IN DATABASE ONLINE_RETAIL_DB;

CREATE WAREHOUSE RETAIL_WH
WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

SHOW WAREHOUSES;

USE WAREHOUSE RETAIL_WH;

USE DATABASE ONLINE_RETAIL_DB;

USE SCHEMA RETAIL_SCHEMA;

CREATE TABLE ONLINE_RETAIL_TABLE (
    InvoiceNo VARCHAR(30),
    StockCode VARCHAR(30),
    Description VARCHAR(500),
    Quantity NUMBER(38,0),
    InvoiceDate TIMESTAMP_NTZ,
    UnitPrice NUMBER(12,4),
    CustomerID NUMBER(38,0),
    Country VARCHAR(100),
    Revenue NUMBER(14,4)
);

DESC TABLE ONLINE_RETAIL_TABLE;

CREATE FILE FORMAT RETAIL_CSV_FORMAT
TYPE = 'CSV'
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE
NULL_IF = ('NULL', 'null')
TIMESTAMP_FORMAT = 'MM/DD/YYYY HH24:MI:SS';

SHOW FILE FORMATS IN SCHEMA ONLINE_RETAIL_DB.RETAIL_SCHEMA;

CREATE STAGE RETAIL_STAGE
FILE_FORMAT = RETAIL_CSV_FORMAT;

SHOW STAGES IN SCHEMA ONLINE_RETAIL_DB.RETAIL_SCHEMA;

LIST @RETAIL_STAGE;

COPY INTO ONLINE_RETAIL_TABLE
FROM @RETAIL_STAGE
FILE_FORMAT = (FORMAT_NAME = 'RETAIL_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_ROWS
FROM ONLINE_RETAIL_TABLE;

SELECT *
FROM ONLINE_RETAIL_TABLE
LIMIT 10;

SELECT *
FROM ONLINE_RETAIL_TABLE;

DESC TABLE ONLINE_RETAIL_TABLE;

SELECT SUM(REVENUE) AS TOTAL_REVENUE
FROM ONLINE_RETAIL_TABLE;

SELECT COUNT(*) AS MISSING_CUSTOMER_IDS
FROM ONLINE_RETAIL_TABLE
WHERE CUSTOMERID IS NULL;

DROP DATABASE ONLINE_RETAIL_DB;

DROP WAREHOUSE RETAIL_WH;

SHOW DATABASES;

SHOW WAREHOUSES;